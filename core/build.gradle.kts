// AppWall's pure core: decisions and calculations with no Android, so they can be tested on the
// JVM in seconds. Android's classes aren't on this module's classpath at all.
plugins {
    // No version: this comes from the Kotlin plugin jar the root build already loads for
    // kotlin.android, so it needs nothing extra from the network.
    id("org.jetbrains.kotlin.jvm")
    // Test-time coverage (ships with Gradle; its agent comes from Maven Central). See CLAUDE.md.
    jacoco
}

jacoco {
    toolVersion = "0.8.12"
}

// The core is where the logic lives, so its coverage may not slip. Run by `check`.
tasks.jacocoTestCoverageVerification {
    dependsOn(tasks.test)
    violationRules {
        rule {
            limit {
                counter = "LINE"
                minimum = "0.95".toBigDecimal()
            }
        }
    }
}

tasks.check {
    dependsOn(tasks.jacocoTestCoverageVerification)
}

tasks.jacocoTestReport {
    dependsOn(tasks.test)
    reports {
        xml.required = true
        html.required = true
    }
}

kotlin {
    jvmToolchain(17)
}

dependencies {
    // Test-only (never in the APK); brings hamcrest-core 1.3. See CLAUDE.md for allowed dependencies.
    testImplementation("junit:junit:4.13.2")
}

// Mutation testing with PIT, run straight from its official jar (no third-party Gradle plugin).
// Test-time only; see CLAUDE.md. Report: core/build/reports/pitest/index.html
val pitest: Configuration by configurations.creating

dependencies {
    pitest("org.pitest:pitest-command-line:1.30.0")
}

tasks.register<JavaExec>("pitest") {
    group = "verification"
    description = "Mutation-tests :core with PIT."
    dependsOn(tasks.testClasses)
    val reportDir = layout.buildDirectory.dir("reports/pitest")
    val testClasspath = sourceSets.test.get().runtimeClasspath
    inputs.files(testClasspath)
    outputs.dir(reportDir)
    classpath = pitest
    mainClass = "org.pitest.mutationtest.commandline.MutationCoverageReport"
    argumentProviders.add(CommandLineArgumentProvider {
        listOf(
            "--targetClasses", "dev.appwall.core.*",
            "--targetTests", "dev.appwall.core.*",
            // Tests share the code's packages; mutate only the code.
            "--excludedClasses", "*Test,*Test\$*,dev.appwall.core.state.FakeScheduler*",
            "--sourceDirs", file("src/main/kotlin").path,
            "--classPath", testClasspath.files.joinToString(","),
            "--reportDir", reportDir.get().asFile.path,
            "--outputFormats", "HTML,XML",
            "--timestampedReports", "false",
            // Generated by the Kotlin compiler for data classes, not written by us.
            "--excludedMethods", "toString,hashCode,equals,component*,copy,copy\$default",
            // Today's score is 78%; raise this as tests improve, never lower it.
            "--mutationThreshold", "75",
            "--threads", Runtime.getRuntime().availableProcessors().toString(),
        )
    })
}
